    failed = False
    cache = {}
    for name, old, new, count in EDITS:
        path = FRAMER / name
        s = cache.setdefault(path, path.read_text(encoding='utf8'))
        n = s.count(old)
        if n == count:
            cache[path] = s.replace(old, new)
        elif n == 0 and new in s:
            pass  # already applied
        else:
            failed = True
            print(f'FAIL {name}: expected {count}x, found {n}x: {old[:80]}', file=sys.stderr)
    if failed:
        sys.exit(1)
    for path, s in cache.items():
        path.write_text(s, encoding='utf8', newline='')
    print(f'applied {len(EDITS)} edits to {len(cache)} files')


