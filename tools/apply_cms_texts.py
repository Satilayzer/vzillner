def set_field(item, key, value):
    t = RICHTEXT if key == CONTENT else STRING
    v = (RICHTEXT, (1, value)) if t == RICHTEXT else (STRING, value)
    for i, (k, _) in enumerate(item):
        if k == key:
            item[i] = (k, v)
            return
    raise KeyError(key)


def main():
    js = MODULE.read_text(encoding='utf8')
    for locale, changes in CHANGES.items():
        chunk_path = FRAMER / f'Bzbs7oMUB-chunk-{locale}-0.framercms'
        index_path = FRAMER / f'Bzbs7oMUB-indexes-{locale}-0.framercms'
        items = read_chunk(chunk_path.read_bytes())
        by_slug = {dict(it)[SLUG][1]: it for it in items}
        for slug, fields in changes.items():
            for key, value in fields.items():
                set_field(by_slug[slug], key, value)
        chunk, pointers = write_chunk(items)

        old_index = index_path.read_bytes()
        pattern = re.compile(r'range:\{from:(\d+),to:(\d+)\}(,url:new URL\(`\./Bzbs7oMUB-indexes-%s-0\.framercms`)' % locale)
        parts, new_ranges = [], []
        for m in pattern.finditer(js):
            collation, names, _ = read_index(old_index[int(m.group(1)):int(m.group(2))])
            start = sum(map(len, parts))
            parts.append(build_index(collation, names, items, pointers))
            new_ranges.append((start, start + len(parts[-1])))
        assert parts, f'no index ranges found for {locale}'
        ranges = iter(new_ranges)
        js = pattern.sub(lambda m: 'range:{from:%d,to:%d}%s' % (*next(ranges), m.group(3)), js)

        chunk_path.write_bytes(chunk)
        index_path.write_bytes(b''.join(parts))
        print(f'{locale}: {len(changes)} items updated, {len(parts)} indexes rebuilt')
    MODULE.write_text(js, encoding='utf8', newline='')


if __name__ == '__main__':
    main()
