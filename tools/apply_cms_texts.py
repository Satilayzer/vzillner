def p(text):
    return [4, 'p', {'dir': 'auto'}, [5, text]]


def ul(*items):
    return [4, 'ul', {'dir': 'auto'}, *[[4, 'li', {'data-preset-tag': 'p'}, [4, 'p', None, [5, t]]] for t in items]]


